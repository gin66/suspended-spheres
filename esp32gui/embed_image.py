Import("env")
import os

src = os.environ.get("SS_FLY_IMAGE", "")
release = os.environ.get("SS_RELEASE", "")
bench = os.environ.get("SS_BENCH_CONSOLE", "")
out = os.path.join(env.subst("$PROJECT_DIR"), "src", "fly_image_data.h")
data = b""
if release and release != "0" and not (bench and bench != "0"):
    if src:
        print("embed_image: release build; embedded Fly image disabled")
    src = ""
if src:
    try:
        with open(src, "rb") as f:
            data = f.read()
        print("embed_image: %d bytes from %s" % (len(data), src))
    except OSError as e:
        print("embed_image: cannot read %s: %s" % (src, e))

with open(out, "w") as f:
    f.write("/* generated by embed_image.py; do not edit */\n")
    f.write("#pragma once\n")
    if data:
        f.write("static const unsigned char kFlyImage[] = {\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
        f.write("};\n")
        f.write("static const unsigned int kFlyImageLen = %d;\n" % len(data))
    else:
        f.write("static const unsigned char kFlyImage[] = {0};\n")
        f.write("static const unsigned int kFlyImageLen = 0;\n")
